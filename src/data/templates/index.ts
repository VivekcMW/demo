export function getTemplate(id: string): TemplateDefinition | undefined {
  return templateRegistry[id];
}

export function getTemplatesByType(type: string): TemplateDefinition[] {
  return Object.values(templateRegistry).filter((t) => t.type === type);
}

export function getTemplatesBySpecialty(specialty: string): TemplateDefinition[] {
  return Object.values(templateRegistry).filter((t) =>
    t.metadata.specialties.some((s) => s.toLowerCase() === specialty.toLowerCase())
  );
}

export function getAllTemplates(): TemplateDefinition[] {
  return Object.values(templateRegistry);
}
